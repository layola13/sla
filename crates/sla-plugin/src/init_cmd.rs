//! The `init` command, mirrored from `runSlaInitCommand`
//! (plugin_cli.zig, venue head 6002b386).
//!
//! Failure shapes, mirrored exactly: directory creation
//! (`makePath`) failures fail the whole invocation (Err -> the
//! ABI shell's Failed status), while each scaffold file is created
//! EXCLUSIVELY and its failure is caught per-file — a
//! `File Error: failed to create <path>: <Zig error name>` line on
//! stderr and return code 1, with later files not attempted.

use crate::cli_help::write_command_help;
use crate::cmdio::{zig_basename, zig_error_name, zig_join, CmdWrite};
use std::io::Write;

fn is_help_arg(arg: &[u8]) -> bool {
    arg == b"-h" || arg == b"--help"
}

/// Zig `projectPackageName`.
fn project_package_name(project_path: &str) -> &str {
    if project_path == "." {
        return "app";
    }
    let base = zig_basename(project_path);
    if base.is_empty() || base == "." {
        "app"
    } else {
        base
    }
}

/// Zig `ensureNewFile`: parent dirs, then an exclusive create.
fn ensure_new_file(path: &str, bytes: &[u8]) -> std::io::Result<()> {
    if let Some(dir) = std::path::Path::new(path).parent() {
        if !dir.as_os_str().is_empty() {
            std::fs::create_dir_all(dir)?;
        }
    }
    let mut file = std::fs::OpenOptions::new()
        .write(true)
        .create_new(true)
        .open(path)?;
    file.write_all(bytes)
}

/// Zig `runSlaInitCommand`. Err(()) = invocation failure.
pub fn run_init_command(
    args: &[Vec<u8>],
    option_start: usize,
    stdout: &mut impl CmdWrite,
    stderr: &mut impl CmdWrite,
) -> Result<u8, ()> {
    let mut project_path: Option<String> = None;
    let mut idx = option_start;
    while idx < args.len() {
        let arg = &args[idx];
        if is_help_arg(arg) {
            write_command_help(stderr, "init")?;
            return Ok(0);
        }
        if arg.starts_with(b"-") {
            stderr.print(format_args!(
                "Unknown sla init option: {}\n",
                String::from_utf8_lossy(arg)
            ))?;
            write_command_help(stderr, "init")?;
            return Ok(1);
        }
        if project_path.is_some() {
            stderr.print(format_args!(
                "Unexpected sla init argument: {}\n",
                String::from_utf8_lossy(arg)
            ))?;
            write_command_help(stderr, "init")?;
            return Ok(1);
        }
        project_path = Some(String::from_utf8_lossy(arg).into_owned());
        idx += 1;
    }

    let root = project_path.as_deref().unwrap_or(".");
    let package_name = project_package_name(root).to_string();
    std::fs::create_dir_all(root).map_err(|_| ())?;

    let src_dir = zig_join(&[root, "src"]);
    std::fs::create_dir_all(&src_dir).map_err(|_| ())?;

    let manifest_path = zig_join(&[root, "sa.mod"]);
    let main_path = zig_join(&[root, "src", "main.sla"]);
    let gitignore_path = zig_join(&[root, ".gitignore"]);

    let manifest = format!("# generated by sla init\npackage \"{package_name}\"\n");
    if let Err(e) = ensure_new_file(&manifest_path, manifest.as_bytes()) {
        stderr.print(format_args!(
            "File Error: failed to create {manifest_path}: error.{}\n",
            zig_error_name(&e)
        ))?;
        return Ok(1);
    }
    if let Err(e) = ensure_new_file(
        &main_path,
        b"fn main() -> i32 {\n    return 0;\n};\n",
    ) {
        stderr.print(format_args!(
            "File Error: failed to create {main_path}: error.{}\n",
            zig_error_name(&e)
        ))?;
        return Ok(1);
    }
    if let Err(e) = ensure_new_file(
        &gitignore_path,
        b".sla-cache/\n.zig-cache/\n.sa_cache/\nzig-out/\n*.out\n*.sa.bc\n",
    ) {
        stderr.print(format_args!(
            "File Error: failed to create {gitignore_path}: error.{}\n",
            zig_error_name(&e)
        ))?;
        return Ok(1);
    }

    stdout.print(format_args!("Initialized SLA binary project: {root}\n"))?;
    stdout.print(format_args!("Entry: {main_path}\n"))?;
    Ok(0)
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::path::PathBuf;

    struct TempCwd(PathBuf);

    impl TempCwd {
        fn enter(tag: &str) -> TempCwd {
            let dir = std::env::temp_dir().join(format!(
                "sla_init_cmd_{}_{}",
                tag,
                std::process::id()
            ));
            let _ = std::fs::remove_dir_all(&dir);
            std::fs::create_dir_all(&dir).unwrap();
            std::env::set_current_dir(&dir).unwrap();
            TempCwd(dir)
        }
    }

    impl Drop for TempCwd {
        fn drop(&mut self) {
            let _ = std::env::set_current_dir("/");
            let _ = std::fs::remove_dir_all(&self.0);
        }
    }

    fn init_args(extra: &[&str]) -> Vec<Vec<u8>> {
        let mut args: Vec<Vec<u8>> = vec![b"sa".to_vec(), b"sla".to_vec(), b"init".to_vec()];
        args.extend(extra.iter().map(|s| s.as_bytes().to_vec()));
        args
    }

    #[test]
    fn init_scaffolds_three_files_then_repeat_fails() {
        let _guard = TempCwd::enter("basic");
        let args = init_args(&["proj"]);
        let mut out: Vec<u8> = Vec::new();
        let mut err: Vec<u8> = Vec::new();
        let rc = run_init_command(&args, 3, &mut out, &mut err).unwrap();
        assert_eq!(rc, 0);
        assert_eq!(
            String::from_utf8(out).unwrap(),
            "Initialized SLA binary project: proj\nEntry: proj/src/main.sla\n"
        );
        assert_eq!(
            std::fs::read_to_string("proj/sa.mod").unwrap(),
            "# generated by sla init\npackage \"proj\"\n"
        );
        assert_eq!(
            std::fs::read_to_string("proj/src/main.sla").unwrap(),
            "fn main() -> i32 {\n    return 0;\n};\n"
        );
        assert_eq!(
            std::fs::read_to_string("proj/.gitignore").unwrap(),
            ".sla-cache/\n.zig-cache/\n.sa_cache/\nzig-out/\n*.out\n*.sa.bc\n"
        );

        // Repeat: the manifest already exists -> File Error, rc 1.
        let mut out: Vec<u8> = Vec::new();
        let mut err: Vec<u8> = Vec::new();
        let rc = run_init_command(&args, 3, &mut out, &mut err).unwrap();
        assert_eq!(rc, 1);
        assert!(out.is_empty());
        assert_eq!(
            String::from_utf8(err).unwrap(),
            "File Error: failed to create proj/sa.mod: error.PathAlreadyExists\n"
        );
    }
}
