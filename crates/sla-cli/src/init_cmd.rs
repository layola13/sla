//! `sla init` — mirror of `runSlaInitCommand` in plugin_cli.zig
//! (venue head 2cc12ea8): scaffold sa.mod + src/main.sla +
//! .gitignore with exclusive creation, the exact stdout lines,
//! and the per-file `File Error:` lines on stderr.

use crate::cli_help::write_command_help;
use crate::options::is_help_arg;
use crate::out::zig_error_name;
use std::io::Write;

/// Zig `std.fs.path.join` for the init path shapes (same leading
/// `./` behavior the A0 slice proved live: join(".", "src",
/// "main.sla") == "./src/main.sla").
fn zig_join(parts: &[&str]) -> String {
    let mut segs: Vec<&str> = Vec::new();
    let absolute = parts.first().map(|p| p.starts_with('/')).unwrap_or(false);
    let leading_dot = parts
        .first()
        .map(|p| p.split('/').next() == Some("."))
        .unwrap_or(false);
    for part in parts {
        for seg in part.split('/') {
            match seg {
                "" | "." => {}
                ".." => {
                    if !segs.is_empty() && segs.last().map(|s| *s != "..").unwrap_or(false) {
                        segs.pop();
                    } else if !absolute {
                        segs.push("..");
                    }
                }
                s => segs.push(s),
            }
        }
    }
    if segs.is_empty() {
        return if absolute { "/".to_string() } else { ".".to_string() };
    }
    let mut out = if absolute {
        "/".to_string()
    } else if leading_dot {
        "./".to_string()
    } else {
        String::new()
    };
    out.push_str(&segs.join("/"));
    out
}

fn zig_basename(path: &str) -> &str {
    let trimmed = path.trim_end_matches('/');
    if trimmed.is_empty() {
        return if path.is_empty() { "" } else { "/" };
    }
    match trimmed.rfind('/') {
        Some(idx) => &trimmed[idx + 1..],
        None => trimmed,
    }
}

/// Zig `projectPackageName`.
fn project_package_name(project_path: &str) -> &str {
    if project_path == "." {
        return "app";
    }
    let base = zig_basename(project_path);
    if base.is_empty() || base == "." {
        return "app";
    }
    base
}

fn ensure_new_file(path: &str, bytes: &[u8]) -> std::io::Result<()> {
    if let Some(idx) = path.rfind('/') {
        let dir = &path[..idx];
        if !dir.is_empty() {
            std::fs::create_dir_all(dir)?;
        }
    }
    let mut f = std::fs::OpenOptions::new()
        .write(true)
        .create_new(true)
        .open(path)?;
    f.write_all(bytes)
}

/// Zig `runSlaInitCommand`. `args` includes the command word at
/// index 0; `option_start` is 1.
pub fn run_init_command(
    args: &[Vec<u8>],
    option_start: usize,
    stdout: &mut impl Write,
    stderr: &mut impl Write,
) -> u8 {
    let mut project_path: Option<String> = None;
    let mut idx = option_start;
    while idx < args.len() {
        let arg = &args[idx];
        if is_help_arg(arg) {
            let _ = write_command_help(stderr, "init");
            return 0;
        }
        if arg.starts_with(b"-") {
            let _ = writeln!(
                stderr,
                "Unknown sla init option: {}",
                crate::out::lossy(arg)
            );
            let _ = write_command_help(stderr, "init");
            return 1;
        }
        if project_path.is_some() {
            let _ = writeln!(
                stderr,
                "Unexpected sla init argument: {}",
                crate::out::lossy(arg)
            );
            let _ = write_command_help(stderr, "init");
            return 1;
        }
        project_path = Some(crate::out::lossy(arg));
        idx += 1;
    }

    let root = project_path.unwrap_or_else(|| ".".to_string());
    let package_name = project_package_name(&root).to_string();
    if std::fs::create_dir_all(&root).is_err() {
        // Zig: makePath failure propagates as a hard failure; the
        // command surface has no printed line for it.
        return 1;
    }
    let src_dir = zig_join(&[&root, "src"]);
    let _ = std::fs::create_dir_all(&src_dir);
    let manifest_path = zig_join(&[&root, "sa.mod"]);
    let main_path = zig_join(&[&root, "src", "main.sla"]);
    let gitignore_path = zig_join(&[&root, ".gitignore"]);

    let manifest = format!("# generated by sla init\npackage \"{package_name}\"\n");
    if let Err(err) = ensure_new_file(&manifest_path, manifest.as_bytes()) {
        let _ = writeln!(
            stderr,
            "File Error: failed to create {manifest_path}: error.{}",
            zig_error_name(&err)
        );
        return 1;
    }
    if let Err(err) = ensure_new_file(
        &main_path,
        b"fn main() -> i32 {\n    return 0;\n};\n",
    ) {
        let _ = writeln!(
            stderr,
            "File Error: failed to create {main_path}: error.{}",
            zig_error_name(&err)
        );
        return 1;
    }
    if let Err(err) = ensure_new_file(
        &gitignore_path,
        b".sla-cache/\n.zig-cache/\n.sa_cache/\nzig-out/\n*.out\n*.sa.bc\n",
    ) {
        let _ = writeln!(
            stderr,
            "File Error: failed to create {gitignore_path}: error.{}",
            zig_error_name(&err)
        );
        return 1;
    }

    let _ = writeln!(stdout, "Initialized SLA binary project: {root}");
    let _ = writeln!(stdout, "Entry: {main_path}");
    0
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn join_and_package_name() {
        assert_eq!(zig_join(&[".", "src", "main.sla"]), "./src/main.sla");
        assert_eq!(zig_join(&["proj", "src"]), "proj/src");
        assert_eq!(project_package_name("."), "app");
        assert_eq!(project_package_name("my/app"), "app");
        assert_eq!(project_package_name("tool"), "tool");
    }

    #[test]
    fn init_scaffolds_and_repeat_fails_like_zig() {
        let dir = std::env::temp_dir().join(format!("sla_cli_init_{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&dir);
        let root = dir.to_string_lossy().into_owned();
        let args: Vec<Vec<u8>> = vec![b"init".to_vec(), root.clone().into_bytes()];
        let (mut out, mut err) = (Vec::new(), Vec::new());
        assert_eq!(run_init_command(&args, 1, &mut out, &mut err), 0);
        let text = String::from_utf8(out).unwrap();
        assert!(text.contains("Initialized SLA binary project:"));
        assert!(std::path::Path::new(&root).join("sa.mod").exists());
        assert!(std::path::Path::new(&root).join("src/main.sla").exists());
        // Second run: exclusive create fails on sa.mod first.
        let (mut out, mut err) = (Vec::new(), Vec::new());
        assert_eq!(run_init_command(&args, 1, &mut out, &mut err), 1);
        let text = String::from_utf8(err).unwrap();
        assert!(text.contains("File Error: failed to create"), "{text}");
        assert!(text.contains("error.PathAlreadyExists"), "{text}");
        let _ = std::fs::remove_dir_all(&dir);
    }
}
